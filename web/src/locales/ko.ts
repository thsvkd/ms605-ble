/** Match every translation key and interpolation signature without fixing Korean literal values. */
type TranslationShape<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends string
    ? string
    : { [K in keyof T]: TranslationShape<T[K]> }

export type Strings = TranslationShape<typeof ko>
